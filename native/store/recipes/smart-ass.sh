# Smart-ass (https://github.com/ffseestevanli-oss/smart-ass): an offline
# dictionary, a std-only Rust engine (core/) behind a small QML window.
# Run by build-apps.sh (see ../README.md).
#
# On Linux, cxx-qt builds the window and its Backend object. Here the engine
# alone is Rust (plain rustc, like Sasha's and Bonk's cores) and a few lines of
# C++ stand in for cxx-qt's part: the same Backend (lookup, suggest, exists,
# word for word what src/backend.rs does) and the same main(). The dictionary
# is baked in at build time, as on Linux, by the engine's own builder run on
# the build machine.

