cat > "$w/backend.h" <<'CPP'
// Generated by native/store/recipes/smart-ass.sh
#pragma once
#include <QObject>
#include <QString>
extern "C" {
const char *smartass_lookup(const char *query, const char *muted, const char *accent);
const char *smartass_suggest(const char *prefix);
int smartass_exists(const char *query);
}
class Backend : public QObject
{
    Q_OBJECT
public:
    using QObject::QObject;
    Q_INVOKABLE QString lookup(const QString &query, const QString &muted, const QString &accent) const
    {
        return QString::fromUtf8(smartass_lookup(query.toUtf8().constData(), muted.toUtf8().constData(), accent.toUtf8().constData()));
    }
    Q_INVOKABLE QString suggest(const QString &prefix) const
    {
        return QString::fromUtf8(smartass_suggest(prefix.toUtf8().constData()));
    }
    Q_INVOKABLE bool exists(const QString &query) const { return smartass_exists(query.toUtf8().constData()) != 0; }
};
CPP
cat > "$w/entry.cpp" <<'CPP'
// Generated by native/store/recipes/smart-ass.sh
#include "backend.h"
#include <QGuiApplication>
#include <QQmlApplicationEngine>
#include <QUrl>
#include <QtQml>

static int smartassMain(int argc, char **argv)
{
    // Fusion follows the desktop's light/dark palette; the default "Basic" style does not.
    if (qEnvironmentVariableIsEmpty("QT_QUICK_CONTROLS_STYLE"))
        qputenv("QT_QUICK_CONTROLS_STYLE", "Fusion");
    QGuiApplication app(argc, argv);
    QGuiApplication::setDesktopFileName(QStringLiteral("smart-ass"));
    qmlRegisterType<Backend>("smartass.backend", 1, 0, "Backend");
    // The store installs main.qml into share/smart-ass.
    QByteArray data = qgetenv("XDG_DATA_HOME");
    if (data.isEmpty())
        data = qgetenv("HOME") + "/.local/share";
    QQmlApplicationEngine engine;
    engine.load(QUrl::fromLocalFile(QString::fromLocal8Bit(data) + QStringLiteral("/smart-ass/main.qml")));
    if (engine.rootObjects().isEmpty())
        return 1;
    return app.exec();
}
CPP
