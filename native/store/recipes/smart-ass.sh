  --target aarch64-linux-android "$core/src/lib.rs" -o "$w/libsmartass_core.rlib"
cat > "$w/ffi.rs" <<'RS'
// Generated by native/store/recipes/smart-ass.sh: src/backend.rs as C functions.
use smartass_core::render::{self, Theme};
use smartass_core::Dictionary;
use std::cell::RefCell;
use std::ffi::{c_char, c_int, CStr, CString};
use std::sync::OnceLock;

static DICT_BYTES: &[u8] = include_bytes!(env!("SMARTASS_DICT_BIN"));
static DICT: OnceLock<Dictionary<'static>> = OnceLock::new();

fn dict() -> &'static Dictionary<'static> {
    DICT.get_or_init(|| Dictionary::new(DICT_BYTES).expect("embedded dictionary is corrupt"))
}

thread_local! {
    static OUT: RefCell<CString> = RefCell::new(CString::default());
}

fn arg(p: *const c_char) -> String {
    if p.is_null() {
        return String::new();
    }
    unsafe { CStr::from_ptr(p) }.to_string_lossy().into_owned()
}

/// Valid until the next call on this thread; the caller copies it.
fn ret(s: String) -> *const c_char {
    OUT.with(|o| {
        *o.borrow_mut() = CString::new(s.replace('\0', "")).unwrap_or_default();
        o.borrow().as_ptr()
    })
}

#[no_mangle]
pub extern "C" fn smartass_lookup(query: *const c_char, muted: *const c_char, accent: *const c_char) -> *const c_char {
    let theme = Theme { muted: arg(muted), accent: arg(accent) };
    let q = arg(query);
    let html = if q.trim().is_empty() {
        render::hint_html(&theme)
    } else {
        match dict().lookup(&q) {
            Some(entry) => render::entry_html(&entry, &theme),
            None => render::not_found_html(&q, &dict().suggest(&q, 8), &theme),
        }
    };
    ret(html)
}

#[no_mangle]
pub extern "C" fn smartass_suggest(prefix: *const c_char) -> *const c_char {
    ret(dict().suggest(&arg(prefix), 6).join("\n"))
}

#[no_mangle]
pub extern "C" fn smartass_exists(query: *const c_char) -> c_int {
    dict().contains(&arg(query)) as c_int
}
RS
SMARTASS_DICT_BIN="$w/dict.bin" rustc --edition "${edition:-2021}" --crate-type staticlib --crate-name smartass_ffi -C opt-level=3 \
