cat > "$w/mkdict.rs" <<'RS'
fn main() {
    let a: Vec<String> = std::env::args().collect();
    let (blob, stats) = smartass_core::builder::build_from_dir(std::path::Path::new(&a[1])).expect("WordNet");
    if stats.skipped_refs > 0 {
        eprintln!("{} dictionary index entries pointed at missing synsets and were skipped", stats.skipped_refs);
    }
    std::fs::write(&a[2], blob).expect("dict.bin");
}
RS
