# Sasha (https://github.com/ffseestevanli-oss/sasha): a music player with a
# Rust core and a Qt 6 / QML window. Run by build-apps.sh (see ../README.md).
#
# On Linux, Cargo builds Sasha as a program whose main() (Rust) hands the QML
# to the Qt host (cpp/host.cpp). Here the Rust side becomes a static library
# (it has no crate dependencies, so plain rustc does), and the Qt host, the
# QML and QtHost's entry point become libsasha.so, which QtHost starts in an
# app_process like DeskDroid's other apps.

src="$STORE_SRC/sasha"
[ -e "$src/Cargo.toml" ] || src="$STORE_SRC"
w="$STORE_WORK"
edition="$(sed -n 's/^edition = "\(.*\)"/\1/p' "$src/Cargo.toml" | head -1)"
version="$(sed -n 's/^version = "\(.*\)"/\1/p' "$src/Cargo.toml" | head -1)"
# Every commit is a new version for the store, which updates on a new version.
store_version="$version+git.${STORE_SHA:0:7}"
echo "Sasha $store_version"

# The Rust core: tn_* functions the Qt host calls.
rustup target add aarch64-linux-android
rustc --edition "${edition:-2021}" --crate-type staticlib --crate-name sasha_core -C opt-level=3 \
  --target aarch64-linux-android -A dead_code "$src/src/main.rs" -o "$w/libsasha_core.a"

# QtHost's entry point calls the host with the QML, as main.rs does.
python3 - "$src/qml/main.qml" > "$w/entry.cpp" <<'PY'
import sys
qml = open(sys.argv[1], 'rb').read()
print('// Generated by native/store/recipes/sasha.sh')
print('#include <QtGlobal>\n#include <QString>\n#include <cstddef>')
print('extern "C" int tn_host_main(int argc, char **argv, const char *qml, size_t qmlLen);')
print('static const unsigned char sashaQml[] = {')
for i in range(0, len(qml), 24):
    print(''.join(f'{b},' for b in qml[i:i + 24]))
print('};')
print('static int sashaMain(int argc, char **argv) { return tn_host_main(argc, argv, reinterpret_cast<const char *>(sashaQml), sizeof sashaQml); }')
PY
entry="$(dirname "$0")/../../plasma/kwin-nativedesk/qthost_entry.cpp"
sed -e 's/args.push_back("kwin_wayland")/args.push_back("sasha")/' -e 's/return kwinMain(/return sashaMain(/' "$entry" >> "$w/entry.cpp"
! grep -q -e kwinMain -e '"kwin_wayland"' "$w/entry.cpp"

cat > "$w/CMakeLists.txt" <<CMAKE
cmake_minimum_required(VERSION 3.21)
project(sasha LANGUAGES CXX)
set(CMAKE_CXX_STANDARD 17)
set(CMAKE_AUTOMOC ON)
find_package(Qt6 REQUIRED COMPONENTS Core Gui Widgets Qml Quick Multimedia DBus)
add_library(sasha SHARED "$src/cpp/host.cpp" "$src/cpp/player.cpp" "$src/cpp/player.h" entry.cpp)
set_target_properties(sasha PROPERTIES CXX_VISIBILITY_PRESET default SUFFIX ".so")
# 16 KB pages (newer phones) need 16 KB-aligned segments, like the APK's libraries.
target_link_options(sasha PRIVATE "-Wl,-z,max-page-size=16384")
target_include_directories(sasha PRIVATE "$src/cpp")
target_compile_definitions(sasha PRIVATE TN_VERSION="$version" TN_ASSET_DIR="/nonexistent")
target_link_libraries(sasha PRIVATE "$w/libsasha_core.a" Qt6::Widgets Qt6::Quick Qt6::Qml Qt6::Multimedia Qt6::DBus log dl)
install(TARGETS sasha LIBRARY DESTINATION lib)
CMAKE

PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig" \
cmake -S "$w" -B "$w/build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_TOOLCHAIN_FILE="$PREFIX/lib/cmake/Qt6/qt.toolchain.cmake" -DQT_HOST_PATH="$QT_HOST_PATH" \
  -DCMAKE_INSTALL_PREFIX="$PREFIX" -DCMAKE_INSTALL_LIBDIR=lib \
  -DCMAKE_FIND_ROOT_PATH="$PREFIX" -DCMAKE_PREFIX_PATH="$PREFIX" \
  -DCMAKE_FIND_ROOT_PATH_MODE_INCLUDE=BOTH -DCMAKE_FIND_ROOT_PATH_MODE_LIBRARY=BOTH
cmake --build "$w/build" -j "$(nproc)"
cmake --install "$w/build"

# Menu entry, icons and version for the store and Plasma's menu.
mkdir -p "$PREFIX/share/applications" "$PREFIX/share/icons/hicolor/scalable/apps" \
  "$PREFIX/share/icons/hicolor/128x128/apps" "$PREFIX/share/metainfo"
cat > "$PREFIX/share/applications/sasha.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=Sasha
GenericName=Music Player
Comment=Play your music library by album, artist or genre
Exec=sasha %F
