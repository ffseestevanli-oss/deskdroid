# Bonk! Model Prop-inator! (https://github.com/ffseestevanli-oss/bonk): a
# Hammer-style brush modeler with a Rust core and a Qt 6 Widgets window.
# Run by build-apps.sh (see ../README.md).
#
# Built like Sasha: Cargo's program becomes a Rust static library (no crate
# dependencies, so plain rustc does), and the Qt host (cpp/host.cpp) plus
# QtHost's entry point become libbonk.so. Three things change for the phone:
#   - OpenGL ES 3.0 instead of desktop OpenGL 3.3 core: the shaders' header
#     becomes "#version 300 es" with default precision (the shaders and the GL
#     calls Bonk makes are otherwise valid ES 3.0), and Qt is asked for ES.
#   - Bonk finds its icons next to its binary, which here is app_process in
#     /system/bin, so they are read from share/bonk instead.
#   - Compiling a model with studiomdl needs Proton, which the phone doesn't
#     have; modeling, saving and exporting work, compiling reports the error.

src="$STORE_SRC"
w="$STORE_WORK"
edition="$(sed -n 's/^edition = "\(.*\)"/\1/p' "$src/Cargo.toml" | head -1)"
version="$(sed -n 's/^version = "\(.*\)"/\1/p' "$src/Cargo.toml" | head -1)"
store_version="$version+git.${STORE_SHA:0:7}"
echo "Bonk $store_version"

python3 - "$src" <<'PY'
import re, sys
src = sys.argv[1]
def patch(path, old, new, count=1):
    p = f'{src}/{path}'
    t = open(p).read()
    n = t.count(old)
    if n != count:
        sys.exit(f'bonk recipe: expected {count} of {old!r} in {path}, found {n}')
    open(p, 'w').write(t.replace(old, new))

# GLSL ES 3.00 shaders.
patch('src/render.rs', '#version 330 core\n', '#version 300 es\nprecision highp float;\nprecision highp int;\n', 4)
# An OpenGL ES 3.0 context.
patch('cpp/host.cpp', '    fmt.setVersion(3, 3);\n    fmt.setProfile(QSurfaceFormat::CoreProfile);\n',
      '    fmt.setRenderableType(QSurfaceFormat::OpenGLES);\n    fmt.setVersion(3, 0);\n')
# Icons from share/bonk (bonk_store.h).
patch('cpp/host.cpp', 'QCoreApplication::applicationDirPath()', 'bonkStoreDir()', 2)
# An entry point taking argc/argv from QtHost: Rust's std::env::args() is
# empty in a library on Android. Same panic hook as main().
p = f'{src}/src/main.rs'
t = open(p).read()
assert 'fn bonk_qt_run(argc: *mut c_int, argv: *mut *mut c_char) -> c_int;' in t
t += '''
#[no_mangle]
pub extern "C" fn bonk_store_main(argc: c_int, argv: *mut *mut c_char) -> c_int {
    std::panic::set_hook(Box::new(|info| {
        eprintln!("{info}");
        write_crash(&format!("panic: {info}"));
    }));
    let mut argc = argc;
    unsafe { bonk_qt_run(&mut argc, argv) }
}
'''
open(p, 'w').write(t)
PY

cat > "$w/bonk_store.h" <<'H'
// Forced into host.cpp by native/store/recipes/bonk.sh: Bonk's data folder.
#pragma once
#include <QByteArray>
#include <QString>
static inline QString bonkStoreDir()
{
    QByteArray d = qgetenv("XDG_DATA_HOME");
    if (d.isEmpty())
        d = qgetenv("HOME") + "/.local/share";
    return QString::fromLocal8Bit(d) + QStringLiteral("/bonk");
}
H

rustup target add aarch64-linux-android
CARGO_PKG_VERSION="$version" rustc --edition "${edition:-2021}" --crate-type staticlib --crate-name bonk_core -C opt-level=3 \
  --target aarch64-linux-android -A dead_code "$src/src/main.rs" -o "$w/libbonk_core.a"

{
  echo '// Generated by native/store/recipes/bonk.sh'
  echo '#include <QtGlobal>'
  echo 'extern "C" int bonk_store_main(int argc, char **argv);'
  echo 'static int bonkMain(int argc, char **argv) { return bonk_store_main(argc, argv); }'
} > "$w/entry.cpp"
entry="$(dirname "$0")/../../plasma/kwin-nativedesk/qthost_entry.cpp"
sed -e 's/args.push_back("kwin_wayland")/args.push_back("bonk")/' -e 's/return kwinMain(/return bonkMain(/' "$entry" >> "$w/entry.cpp"
if grep -q -e kwinMain -e '"kwin_wayland"' "$w/entry.cpp"; then echo "::error::QtHost entry not adapted"; exit 1; fi

cat > "$w/CMakeLists.txt" <<CMAKE
cmake_minimum_required(VERSION 3.21)
project(bonk LANGUAGES CXX)
set(CMAKE_CXX_STANDARD 17)
find_package(Qt6 REQUIRED COMPONENTS Core Gui Widgets OpenGL OpenGLWidgets)
add_library(bonk SHARED "$src/cpp/host.cpp" entry.cpp)
set_target_properties(bonk PROPERTIES CXX_VISIBILITY_PRESET default SUFFIX ".so")
# 16 KB pages (newer phones) need 16 KB-aligned segments, like the APK's libraries.
target_link_options(bonk PRIVATE "-Wl,-z,max-page-size=16384")
target_include_directories(bonk PRIVATE "$src/cpp")
target_compile_options(bonk PRIVATE -include "$w/bonk_store.h")
target_compile_definitions(bonk PRIVATE BONK_VERSION="$version")
target_link_libraries(bonk PRIVATE "$w/libbonk_core.a" Qt6::Widgets Qt6::OpenGL Qt6::OpenGLWidgets log dl)
install(TARGETS bonk LIBRARY DESTINATION lib)
CMAKE

PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig" \
cmake -S "$w" -B "$w/build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_TOOLCHAIN_FILE="$PREFIX/lib/cmake/Qt6/qt.toolchain.cmake" -DQT_HOST_PATH="$QT_HOST_PATH" \
  -DCMAKE_INSTALL_PREFIX="$PREFIX" -DCMAKE_INSTALL_LIBDIR=lib \
  -DCMAKE_FIND_ROOT_PATH="$PREFIX" -DCMAKE_PREFIX_PATH="$PREFIX" \
  -DCMAKE_FIND_ROOT_PATH_MODE_INCLUDE=BOTH -DCMAKE_FIND_ROOT_PATH_MODE_LIBRARY=BOTH
cmake --build "$w/build" -j "$(nproc)"
cmake --install "$w/build"

