#!/usr/bin/env python3
"""Android's seccomp policy for apps, as C, for android-sim.c.

android-policy.py <bionic libc folder> <asm/unistd_64.h> <glibc's aarch64/arch-syscall.h>

Bionic generates the filter Android puts on every app (genseccomp.py) from
the system calls bionic itself makes (SYSCALLS.TXT) plus
SECCOMP_ALLOWLIST_{COMMON,APP}.TXT, minus SECCOMP_BLOCKLIST_{COMMON,APP}.TXT;
any other call traps (SIGSYS). This prints, as a C array, the x86_64
numbers of the calls Android allows ARM64 apps, so a desktop machine can
stand in for the phone (android-sim.c): the policy is ARM64's, and x86_64's
old calls that ARM64 doesn't have at all (open, mkdir, stat...; ARM64's
glibc makes openat, mkdirat, fstatat instead) are allowed too."""
import pathlib
import re
import sys

src, unistd, arm64h = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3]
tags = {"all", "arm64", "lp64"}


def names(f):
    out = set()
    for line in (src / f).read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line or "(" not in line:
            continue
        head, _, rest = line.partition("(")
        archs = set(rest.rpartition(")")[2].replace(" ", "").replace("\t", "").split(","))
        if not archs & tags:
            continue
        head = head.split()[-1]  # drop the return type
        names_ = head.split(":")[1] if ":" in head else head
        for n in re.split(r"[,|]", names_):
            out.add(n.strip())
    return out


allowed = names("SYSCALLS.TXT") | names("SECCOMP_ALLOWLIST_COMMON.TXT") | names("SECCOMP_ALLOWLIST_APP.TXT")
allowed -= names("SECCOMP_BLOCKLIST_COMMON.TXT") | names("SECCOMP_BLOCKLIST_APP.TXT")
nrs = {}
for m in re.finditer(r"#define __NR_(\w+)\s+(\d+)", pathlib.Path(unistd).read_text()):
    nrs[m.group(1)] = int(m.group(2))
arm64 = set(re.findall(r"#define __NR_(\w+)", pathlib.Path(arm64h).read_text()))
allowed |= {n for n in nrs if n not in arm64}
known = sorted(nrs[n] for n in allowed if n in nrs)
print("/* generated by android-policy.py */")
print("static const unsigned int android_allowed[] = {")
print("    " + ", ".join(str(n) for n in known))
print("};")
missing = sorted(n for n in allowed if n not in nrs)
print(f"/* not x86_64 calls: {' '.join(missing)} */")
